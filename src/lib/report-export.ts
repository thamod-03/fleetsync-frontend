import type { OperationalReport } from '../types/reporting.ts'

const csvCell = (value: string) => `"${(/^[\s]*[=+@-]/.test(value) ? "'" : '') + value.replaceAll('"', '""')}"`
export function reportCsv(report: OperationalReport): string {
  return [
    [report.filters.type, `${report.filters.start} to ${report.filters.end}`],
    ['Generated by', report.generatedBy, report.generatedAt],
    ['Base', report.filters.base || 'All bases', 'Customer ID', report.filters.customerId || 'All customers'],
    ...report.cards.map((card) => [card.label, card.value, card.note]), [], report.columns,
    ...report.rows.map((row) => row.cells), [], ['Date (UTC)', 'Trips completed'],
    ...report.chart.map((item) => [item.date, String(item.completed)]), [], ...report.notes.map((note) => ['Note', note]),
  ].map((row) => row.map(csvCell).join(',')).join('\r\n')
}

export function downloadReportCsv(report: OperationalReport, filename: string) {
  const url = URL.createObjectURL(new Blob(['\uFEFF' + reportCsv(report)], { type: 'text/csv;charset=utf-8' }))
  const anchor = document.createElement('a'); anchor.href = url; anchor.download = filename
  document.body.append(anchor); anchor.click(); anchor.remove()
  setTimeout(() => URL.revokeObjectURL(url), 0)
}

export function printReport(report: OperationalReport): boolean {
  const page = window.open('', '_blank', 'width=1100,height=800')
  if (!page) return false
  page.opener = null
  const escape = (text: string) => text.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('"', '&quot;')
  const row = (values: string[], tag = 'td') => `<tr>${values.map((value) => `<${tag}>${escape(value)}</${tag}>`).join('')}</tr>`
  page.document.write(`<!doctype html><html><head><title>FleetSync · ${escape(report.filters.type)} · ${escape(report.filters.start)} to ${escape(report.filters.end)}</title><style>body{font:13px sans-serif;color:#111827;margin:32px}table{width:100%;border-collapse:collapse;margin:20px 0}td,th{padding:10px;text-align:left;border:1px solid #ddd}th{background:#f3f4f6}small{color:#555}@page{size:A4 landscape;margin:12mm}</style></head><body><h1>FleetSync · ${escape(report.filters.type)}</h1><p>${escape(report.filters.start)} – ${escape(report.filters.end)} · ${escape(report.generatedBy)} · ${escape(report.generatedAt)}</p><p>Base: ${escape(report.filters.base || 'All bases')} · Customer ID: ${escape(report.filters.customerId || 'All customers')}</p><table>${row(['Metric', 'Value', 'Basis'], 'th')}${report.cards.map((card) => row([card.label, card.value, card.note])).join('')}</table><table>${row(report.columns, 'th')}${report.rows.map((item) => row(item.cells)).join('')}</table><table>${row(['Date (UTC)', 'Trips completed'], 'th')}${report.chart.map((item) => row([item.date, String(item.completed)])).join('')}</table>${report.notes.map((note) => `<p><small>${escape(note)}</small></p>`).join('')}</body></html>`)
  page.document.close(); page.focus(); page.print()
  return true
}
